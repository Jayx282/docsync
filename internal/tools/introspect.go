// IntrospectOptions controls config drafting.
type IntrospectOptions struct {
	Root     config.TableName
	RootKey  string // defaults to the root table's single-column primary key
	Views    string // optional LIKE pattern, e.g. "sync.%": only tables these views read
	MaxDepth int
}

type edge struct {
	child, parent         config.TableName
	childCols, parentCols []string
	guessed               bool // inferred from column names, not a declared foreign key
}

// Introspect drafts a docsync config from foreign keys, column names and
// (optionally) the base tables behind a set of views. Review the output: legacy
// schemas often lack foreign keys, so relationships may be missing or guessed.
func Introspect(ctx context.Context, db *sql.DB, opt IntrospectOptions) (string, error) {
	if opt.MaxDepth == 0 {
		opt.MaxDepth = 3
	}
	cat, err := sqlserver.LoadCatalog(ctx, db, []config.TableName{opt.Root})
	if err != nil {
		return "", err
	}
	root := cat.MustTable(opt.Root)
	if opt.RootKey == "" {
		if len(root.PK) != 1 {
			return "", fmt.Errorf("%s has a %d-column primary key; pass --key", opt.Root, len(root.PK))
		}
		opt.RootKey = root.PK[0]
	}
	edges, err := loadForeignKeys(ctx, db)
	if err != nil {
		return "", err
	}
	tables, err := listTables(ctx, db)
	if err != nil {
		return "", err
	}
	var scope map[string]bool
	var viewTables []config.TableName
	if opt.Views != "" {
		if viewTables, err = viewBaseTables(ctx, db, opt.Views); err != nil {
			return "", err
		}
		scope = map[string]bool{opt.Root.Key(): true}
		for _, t := range viewTables {
			scope[t.Key()] = true
		}
	}
	// Name-based guesses: a column named like the root key in another table.
	declared := map[string]bool{}
	for _, e := range edges {
		declared[e.child.Key()+"→"+e.parent.Key()] = true
	}
	cols, err := columnsNamed(ctx, db, opt.RootKey)
	if err != nil {
		return "", err
	}
	for _, t := range cols {
		if t.Key() == opt.Root.Key() || declared[t.Key()+"→"+opt.Root.Key()] {
			continue
		}
		edges = append(edges, edge{child: t, parent: opt.Root, childCols: []string{opt.RootKey}, parentCols: []string{opt.RootKey}, guessed: true})
	}

	type rule struct {
		table   config.TableName
		next    config.TableName
		join    [][2]string
		kind    string
		guessed bool
		depth   int
	}
	rules := map[string]*rule{}
	order := []string{}
	frontier := []config.TableName{opt.Root}
	visited := map[string]bool{opt.Root.Key(): true}
	for depth := 1; depth <= opt.MaxDepth && len(frontier) > 0; depth++ {
		var next []config.TableName
		for _, node := range frontier {
			for _, e := range edges {
				var other config.TableName
				var r rule
				switch {
				case e.parent.Key() == node.Key() && !visited[e.child.Key()]:
					other = e.child
					r = rule{table: e.child, next: node, kind: config.KindReferences, guessed: e.guessed, depth: depth}
					for i := range e.childCols {
						r.join = append(r.join, [2]string{e.childCols[i], e.parentCols[i]})
					}
				case e.child.Key() == node.Key() && !visited[e.parent.Key()]:
					other = e.parent
					r = rule{table: e.parent, next: node, kind: config.KindReferencedBy, guessed: e.guessed, depth: depth}
					for i := range e.childCols {
						r.join = append(r.join, [2]string{e.parentCols[i], e.childCols[i]})
					}
				default:
					continue
				}
				if scope != nil && !scope[other.Key()] {
					continue
				}
				visited[other.Key()] = true
				rr := r
				rules[other.Key()] = &rr
				order = append(order, other.Key())
				next = append(next, other)
			}
		}
		frontier = next
	}

	// Primary keys and change tracking for every table in the draft.
	var names []config.TableName
	for _, k := range order {
		names = append(names, rules[k].table)
	}
	full, err := sqlserver.LoadCatalog(ctx, db, append([]config.TableName{opt.Root}, names...))
	if err != nil {
		return "", err
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Draft generated by `docsync introspect`. Review every rule before use.\n")
	fmt.Fprintf(&b, "# Rules marked GUESSED come from column names, not foreign keys.\n\n")
	fmt.Fprintf(&b, "source:\n  type: sqlserver\n  dsn_env: DOCSYNC_DSN\n\n")
	fmt.Fprintf(&b, "document:\n  name: %s\n  root: { table: %s, key: [%s] }\n  fragments:\n", strings.ToLower(opt.Root.Name), opt.Root, opt.RootKey)
	fmt.Fprintf(&b, "    - name: details\n      sql: |\n        SELECT r.id AS _root, %s\n        FROM {{roots}} r\n        JOIN %s t ON t.%s = r.id\n",
		columnList("t", sortedColumns(root)), opt.Root, config.QuoteIdent(opt.RootKey))
	for _, k := range order {
		r := rules[k]
		if r.kind != config.KindReferences || r.next.Key() != opt.Root.Key() {
			continue
		}
		ti := full.MustTable(r.table)
		if len(ti.PK) == 0 {
			continue
		}
		fmt.Fprintf(&b, "    - name: %s\n      cardinality: many\n      path: %s\n      sort_key: [%s]\n      sql: |\n        SELECT r.id AS _root, %s\n        FROM {{roots}} r\n        JOIN %s c ON c.%s = r.id\n",
			strings.ToLower(r.table.Name), strings.ToLower(r.table.Name), strings.Join(ti.PK, ", "),
			columnList("c", sortedColumns(ti)), r.table, config.QuoteIdent(r.join[0][0]))
	}
	fmt.Fprintf(&b, "    # Lookup and multi-hop tables below still need columns added to a fragment (usually a LEFT JOIN).\n\n")
	fmt.Fprintf(&b, "routing:\n")
	for _, k := range order {
		r := rules[k]
		ti := full.MustTable(r.table)
		var join []string
		for _, j := range r.join {
			join = append(join, fmt.Sprintf("%s: %s", j[0], j[1]))
		}
		var notes []string
		if r.guessed {
			notes = append(notes, "GUESSED")
		}
		if len(ti.PK) == 0 {
			notes = append(notes, "NO PRIMARY KEY: change tracking needs one")
		}
		if !ti.CTEnabled {
			notes = append(notes, "change tracking OFF")
		}
		comment := ""
		if len(notes) > 0 {
			comment = "  # " + strings.Join(notes, "; ")
		}
		fmt.Fprintf(&b, "  - { table: %s, key: [%s], next: { table: %s, join: { %s }, kind: %s } }%s\n",
			r.table, strings.Join(ti.PK, ", "), r.next, strings.Join(join, ", "), r.kind, comment)
	}
	if opt.Views != "" {
		var unreached []string
		for _, t := range viewTables {
			if t.Key() != opt.Root.Key() && rules[t.Key()] == nil {
				unreached = append(unreached, t.String())
			}
		}
		sort.Strings(unreached)
		if len(unreached) > 0 {
			fmt.Fprintf(&b, "  # TODO: read by %s but not connected to %s by a foreign key or column name:\n", opt.Views, opt.Root)
			for _, u := range unreached {
				fmt.Fprintf(&b, "  #   %s\n", u)
			}
		}
	}
	_ = tables
	fmt.Fprintf(&b, "\nsinks:\n  - { type: parquet_log, dir: ./out/parquet, include_json: true }\n\nstate: { dir: ./state }\n")
	return b.String(), nil
}

func sortedColumns(t *sqlserver.TableInfo) []string {
	// Keep the table's column order stable: sort by name for a deterministic draft.
	var cols []string
	for _, c := range t.Columns {
		cols = append(cols, c.Name)
	}
	sort.Strings(cols)
	return cols
}

func columnList(alias string, cols []string) string {
	var out []string
	for _, c := range cols {
		out = append(out, alias+"."+config.QuoteIdent(c))
	}
	return strings.Join(out, ", ")
}

func loadForeignKeys(ctx context.Context, db *sql.DB) ([]edge, error) {
	rows, err := db.QueryContext(ctx, `
SELECT fk.object_id, SCHEMA_NAME(pt.schema_id), pt.name, pc.name, SCHEMA_NAME(rt.schema_id), rt.name, rc.name
FROM sys.foreign_keys fk
JOIN sys.foreign_key_columns fkc ON fkc.constraint_object_id = fk.object_id
JOIN sys.tables pt ON pt.object_id = fk.parent_object_id
JOIN sys.columns pc ON pc.object_id = fk.parent_object_id AND pc.column_id = fkc.parent_column_id
JOIN sys.tables rt ON rt.object_id = fk.referenced_object_id
JOIN sys.columns rc ON rc.object_id = fk.referenced_object_id AND rc.column_id = fkc.referenced_column_id
ORDER BY fk.object_id, fkc.constraint_column_id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	byFK := map[int64]*edge{}
	var ids []int64
	for rows.Next() {
		var id int64
		var ps, pt, pc, rs, rt, rc string
		if err := rows.Scan(&id, &ps, &pt, &pc, &rs, &rt, &rc); err != nil {
			return nil, err
		}
		e := byFK[id]
		if e == nil {
			e = &edge{child: config.TableName{Schema: ps, Name: pt}, parent: config.TableName{Schema: rs, Name: rt}}
			byFK[id] = e
			ids = append(ids, id)
		}
		e.childCols = append(e.childCols, pc)
		e.parentCols = append(e.parentCols, rc)
	}
	out := make([]edge, 0, len(ids))
	for _, id := range ids {
		out = append(out, *byFK[id])
	}
	return out, rows.Err()
}

func listTables(ctx context.Context, db *sql.DB) ([]config.TableName, error) {
	rows, err := db.QueryContext(ctx, `SELECT SCHEMA_NAME(schema_id), name FROM sys.tables WHERE is_ms_shipped = 0 ORDER BY 1, 2`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []config.TableName
	for rows.Next() {
		var t config.TableName
		if err := rows.Scan(&t.Schema, &t.Name); err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

func columnsNamed(ctx context.Context, db *sql.DB, name string) ([]config.TableName, error) {
	rows, err := db.QueryContext(ctx, `
SELECT SCHEMA_NAME(t.schema_id), t.name FROM sys.columns c JOIN sys.tables t ON t.object_id = c.object_id
WHERE c.name = @p1 AND t.is_ms_shipped = 0 ORDER BY 1, 2`, name)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []config.TableName
	for rows.Next() {
		var t config.TableName
		if err := rows.Scan(&t.Schema, &t.Name); err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

// viewBaseTables lists the base tables read (directly or through nested views)
// by views whose schema-qualified name matches pattern.
func viewBaseTables(ctx context.Context, db *sql.DB, pattern string) ([]config.TableName, error) {
	rows, err := db.QueryContext(ctx, `
WITH v AS (
    SELECT o.object_id FROM sys.views o WHERE SCHEMA_NAME(o.schema_id) + '.' + o.name LIKE @p1
), deps AS (
    SELECT d.referenced_id AS id, 0 AS depth FROM sys.sql_expression_dependencies d JOIN v ON v.object_id = d.referencing_id
    WHERE d.referenced_id IS NOT NULL
    UNION ALL
    SELECT d.referenced_id, deps.depth + 1 FROM sys.sql_expression_dependencies d JOIN deps ON deps.id = d.referencing_id
    WHERE d.referenced_id IS NOT NULL AND deps.depth < 8
)
SELECT DISTINCT SCHEMA_NAME(t.schema_id), t.name FROM deps JOIN sys.tables t ON t.object_id = deps.id
ORDER BY 1, 2`, pattern)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []config.TableName
	for rows.Next() {
		var t config.TableName
		if err := rows.Scan(&t.Schema, &t.Name); err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}
